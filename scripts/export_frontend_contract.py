"""Generate TS wire aliases and the exact B EvidenceBundle schema, with a drift check."""
import argparse
import json
from pathlib import Path
from contracts import models as m

ROOT = Path(__file__).resolve().parents[1]


def ts(schema):
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(x) for x in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(ts(x) for x in schema["anyOf"])
    kind = schema.get("type")
    if kind == "array":
        return "Array<" + ts(schema["items"]) + ">"
    if kind == "object":
        if "properties" in schema:
            required = schema.get("required", [])
            return "{\n" + "\n".join("  " + json.dumps(key) + ("" if key in required else "?") + ": " + ts(value) + ";"
                                         for key, value in schema["properties"].items()) + "\n}"
        extra = schema.get("additionalProperties", next(iter(schema.get("patternProperties", {}).values()), {}))
        return "Record<string, " + (ts(extra) if isinstance(extra, dict) else "unknown") + ">"
    return {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}.get(kind, "unknown")


def products():
    aliases = "// Generated by scripts.export_frontend_contract; do not edit.\n"
    for name, model in vars(m).items():
        if isinstance(model, type) and issubclass(model, m.Wire) and model is not m.Wire:
            aliases += "export type " + name + " = " + ts(model.model_json_schema()) + ";\n\n"
    return {"contract.ts": aliases,
            "evidence.schema.json": json.dumps(m.EvidenceBundle.model_json_schema(), ensure_ascii=False, indent=2) + "\n"}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    folder = ROOT / "frontend/src/generated"
    folder.mkdir(parents=True, exist_ok=True)
    for name, value in products().items():
        path = folder / name
        if args.check:
            assert path.read_text(encoding="utf-8") == value, "Frontend contract drift: " + name
        else:
            path.write_text(value, encoding="utf-8")
    print("Frontend wire types and evidence schema match B models.")


if __name__ == "__main__":
    main()
